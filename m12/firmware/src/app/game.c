void game_text(uint32_t *fb,uint32_t stride_bytes,int x,int y,uint32_t rgb,const char *s,int scale){
 if(!fb||!s||scale<1||scale>8)return;
 for(;*s;s++,x+=8*scale){
  unsigned ch=(unsigned char)*s;if(ch>='a'&&ch<='z')ch-=32;if(ch<32||ch>95)ch='?';
  for(int row=0;row<8;row++)for(int col=0;col<8;col++)if(FONT[ch-32][row]&(128u>>col))
   for(int sy=0;sy<scale;sy++)for(int sx=0;sx<scale;sx++){
    int px=x+col*scale+sx,py=y+row*scale+sy;
    if(px>=0&&px<GAME_W&&py>=0&&py<GAME_H)fb[(size_t)py*(stride_bytes/4)+px]=0xff000000u|rgb;
   }
 }
}

